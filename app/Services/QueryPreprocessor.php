<?php

namespace App\Services;

/**
 * پیش‌پردازش ورودی کاربر قبل از Retrieval.
 *
 * این کلاس عمداً فقط مسئول نرمال‌سازی متن است تا این مسئولیت
 * از لایه Data Access جدا باشد. استخراج keyword/سن/جنسیت در گام بعدی
 * فاز 1 از AiKnowledgeRepository به همین لایه منتقل می‌شود.
 */
class QueryPreprocessor
{
    public function normalize(string $question): string
    {
        $normalized = strtr($question, [
            // حروف عربی -> معادل فارسی
            'ي' => 'ی',
            'ى' => 'ی',
            'ك' => 'ک',

            // اعداد فارسی -> لاتین
            '۰' => '0',
            '۱' => '1',
            '۲' => '2',
            '۳' => '3',
            '۴' => '4',
            '۵' => '5',
            '۶' => '6',
            '۷' => '7',
            '۸' => '8',
            '۹' => '9',

            // اعداد عربی -> لاتین
            '٠' => '0',
            '١' => '1',
            '٢' => '2',
            '٣' => '3',
            '٤' => '4',
            '٥' => '5',
            '٦' => '6',
            '٧' => '7',
            '٨' => '8',
            '٩' => '9',

            // نیم‌فاصله برای جستجوی پایدار به فاصله تبدیل می‌شود
            "\u{200C}" => ' ',
        ]);

        $normalized = (string) preg_replace('/\s+/u', ' ', $normalized);

        return trim($normalized);
    }
}
